// Helper to filter closest local suggestions based on query
export function filterLocationSuggestions(query) {
  if (!query || query.trim() === '') {
    return CITIES_AND_STATES_DB.slice(0, 15);
  }

  const q = query.toLowerCase().trim();

  // First priority: Exact or Starts with query
  const startsWithMatches = CITIES_AND_STATES_DB.filter(
    item => item.name.toLowerCase().startsWith(q) || item.city.toLowerCase().startsWith(q)
  );

  // Second priority: Contains query
  const containsMatches = CITIES_AND_STATES_DB.filter(
    item => !startsWithMatches.includes(item) &&
      (item.name.toLowerCase().includes(q) || item.state.toLowerCase().includes(q))
  );

  const combined = [...startsWithMatches, ...containsMatches];
  return combined.slice(0, 20);
}
